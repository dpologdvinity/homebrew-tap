#!/usr/bin/env bash
# Regenerate Formula/whoisport.rb from the latest whoisport GitHub release.
# Uses the sha256 digests GitHub publishes for release assets, so nothing is downloaded.
set -euo pipefail
repo=dpologdvinity/whoisport
json=$(gh api "repos/$repo/releases/latest")
tag=$(jq -r .tag_name <<<"$json")

asset() { # $1 = target triple; prints "url sha256"
  local name="whoisport-$tag-$1.tar.gz" sha
  sha=$(jq -r --arg n "$name" '.assets[] | select(.name == $n) | .digest // empty' <<<"$json")
  [[ $sha == sha256:* ]] || { echo "no sha256 for $name in $tag" >&2; exit 1; }
  echo "https://github.com/$repo/releases/download/$tag/$name ${sha#sha256:}"
}
read -r mac_arm_url mac_arm_sha <<<"$(asset aarch64-apple-darwin)"
read -r mac_x86_url mac_x86_sha <<<"$(asset x86_64-apple-darwin)"
read -r lin_arm_url lin_arm_sha <<<"$(asset aarch64-unknown-linux-musl)"
read -r lin_x86_url lin_x86_sha <<<"$(asset x86_64-unknown-linux-musl)"

cd "$(dirname "$0")/.."
cat > Formula/whoisport.rb <<EOF
# Generated by scripts/update-whoisport.sh; do not edit by hand.
class Whoisport < Formula
  desc "Show what is listening on a TCP or UDP port, and optionally kill it"
  homepage "https://github.com/$repo"
  version "${tag#v}"
  license "MIT"

  on_macos do
    on_arm do
      url "$mac_arm_url"
      sha256 "$mac_arm_sha"
    end
    on_intel do
      url "$mac_x86_url"
      sha256 "$mac_x86_sha"
    end
  end

  on_linux do
    on_arm do
      url "$lin_arm_url"
      sha256 "$lin_arm_sha"
    end
    on_intel do
      url "$lin_x86_url"
      sha256 "$lin_x86_sha"
    end
  end

  def install
    bin.install "whoisport"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/whoisport --version")
  end
end
EOF
echo "Formula/whoisport.rb -> $tag"
