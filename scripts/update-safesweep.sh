#!/usr/bin/env bash
# Regenerate Formula/safesweep.rb from the latest safesweep GitHub release.
# Uses the sha256 digests GitHub publishes for release assets, so nothing is downloaded.
# safesweep is Linux-only (it reads /proc), so there is no macOS block.
set -euo pipefail
repo=dpologdvinity/safesweep
json=$(gh api "repos/$repo/releases/latest")
tag=$(jq -r .tag_name <<<"$json")

asset() { # $1 = target triple; prints "url sha256"
  local name="safesweep-$tag-$1.tar.gz" sha
  sha=$(jq -r --arg n "$name" '.assets[] | select(.name == $n) | .digest // empty' <<<"$json")
  [[ $sha == sha256:* ]] || { echo "no sha256 for $name in $tag" >&2; exit 1; }
  echo "https://github.com/$repo/releases/download/$tag/$name ${sha#sha256:}"
}
read -r arm_url arm_sha <<<"$(asset aarch64-unknown-linux-musl)"
read -r x86_url x86_sha <<<"$(asset x86_64-unknown-linux-musl)"

cd "$(dirname "$0")/.."
cat > Formula/safesweep.rb <<RB
# Generated by scripts/update-safesweep.sh; do not edit by hand.
class Safesweep < Formula
  desc "Clean caches and temp files that are provably safe to delete"
  homepage "https://github.com/$repo"
  version "${tag#v}"
  license any_of: ["MIT", "Apache-2.0"]

  depends_on :linux

  on_linux do
    on_arm do
      url "$arm_url"
      sha256 "$arm_sha"
    end
    on_intel do
      url "$x86_url"
      sha256 "$x86_sha"
    end
  end

  def install
    bin.install "safesweep"
    bash_completion.install "safesweep.bash" => "safesweep"
    zsh_completion.install "_safesweep"
    fish_completion.install "safesweep.fish"
    man1.install "safesweep.1"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/safesweep --version")
  end
end
RB
